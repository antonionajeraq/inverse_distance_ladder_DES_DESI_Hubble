def anchor_terms(anchor):
    """[(component, H0, sigma), ...] -- the independent Gaussian terms this anchor adds.

    A composite contributes one term per component, which is exactly a diagonal covariance
    between independent probes: they share no rung, no photometry and no host sample."""
    if anchor == 'none':
        return []
    if anchor in RETIRED_ANCHORS:
        raise ValueError('anchor %r has been withdrawn and may not be used in a quoted '
                         'result; see the RETIRED_ANCHORS note.' % anchor)
    if anchor in ANCHOR_SETS:
        return [(c,) + ANCHORS[c] for c in ANCHOR_SETS[anchor]]
    if anchor not in ANCHORS:
        raise ValueError('unknown anchor %r; known: %s'
                         % (anchor, ', '.join(sorted(ANCHORS) + sorted(ANCHOR_SETS))))
    return [(anchor,) + ANCHORS[anchor]]


