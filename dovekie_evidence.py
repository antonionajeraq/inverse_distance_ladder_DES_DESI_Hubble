def task_table(out_path=None):
    """Render Table 2.  lnB10 is formed WITHIN a sample only."""
    R = load_grid()
    if not R:
        raise SystemExit('no cached evidence cells; run --task grid first')
    rows = []
    for s in ('des_only', 'full', 'full_dleg'):
        for a in ('none', 'lfree3', 'breuval'):
            ref = R.get((s, a, 'lcdm'))
            if ref is None:
                print('[table] missing LCDM reference for %s/%s -- skipping' % (s, a))
                continue
            for m in ('exp', 'cpl'):
                r = R.get((s, a, m))
                if r is None:
                    continue
                lnB = r['logz'] - ref['logz']
                sig = float(np.hypot(r['logz_err'], ref['logz_err']))
                p2, p3 = ('A', 'z1') if m == 'exp' else ('w0', 'wa')
                rows.append(dict(
                    sample=s, anchor=a, model=m, lnB=lnB, lnB_err=sig,
                    Om=r['Om_mean'], Om_err=r['Om_std'],
                    p2=r[p2 + '_mean'], p2_err=r[p2 + '_std'],
                    p3=r[p3 + '_mean'], p3_err=r[p3 + '_std'],
                    H0=r['H0_at_0_mean'], H0_err=r['H0_at_0_std'],
                    H0_bg=r.get('H0_mean' if m == 'cpl' else 'H0_LCDM_mean'),
                    P_A_gt_0=r.get('P_A_gt_0'),
                    Delta=r.get('Delta_mean'), Delta_err=r.get('Delta_std')))

    print('\n%-26s %-13s %-5s %10s %14s %16s %16s %16s'
          % ('Sample', 'Anchor', 'Model', 'lnB10', 'Om', 'w0/A', 'wa/z1', 'H(0)'))
    for r in rows:
        print('%-26s %-13s %-5s %+6.2f+-%.2f %7.3f+-%.3f %8.2f+-%-6.2f %8.3f+-%-6.3f '
              '%7.2f+-%.2f'
              % (SAMPLE_LABEL[r['sample']], ANCHOR_LABEL[r['anchor']], r['model'],
                 r['lnB'], r['lnB_err'], r['Om'], r['Om_err'], r['p2'], r['p2_err'],
                 r['p3'], r['p3_err'], r['H0'], r['H0_err']))
    print('\nlnB10 is formed WITHIN a sample only: the global magnitude offset is\n'
          'improper-flat, so lnZ carries an arbitrary additive constant per dataset.\n'
          'The H(0) column is the model\'s present-day rate -- for `exp` that is\n'
          'H0_LCDM + A, not the LCDM background, which stays near 68-70 even where H(0)\n'
          'reaches 73.  The `SNIa-indep.` anchor imposes Jensen, Vogl and GW170817\n'
          'jointly with a diagonal covariance; the `SH0ES` row is SH0ES-CONDITIONAL --\n'
          'Breuval+2024 is a distance ladder whose third rung is the SN Ia sample.')

    for r in rows:
        if r['model'] == 'exp' and r.get('P_A_gt_0') is not None:
            print('  P(A>0)  %-26s %-13s  %.3f'
                  % (SAMPLE_LABEL[r['sample']], ANCHOR_LABEL[r['anchor']],
                     r['P_A_gt_0']))

    out_path = out_path or os.path.join(dc.RESULT_DIR, 'table2_evidence.json')
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w') as fh:
        json.dump(rows, fh, indent=2)
    print('\nwrote', out_path)
    return rows


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('USAGE')[0].strip(),
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--task', choices=('grid', 'table'), default='grid')
    ap.add_argument('--only', nargs='*', help='cells as sample/anchor/model')
    ap.add_argument('--recompute', action='store_true')
    ap.add_argument('--quiet', action='store_true')
    ap.add_argument('--nproc', type=int, default=None,
                    help='worker processes for the likelihood queue (default %d, from '
                         '$NPROC).  Pin OMP_NUM_THREADS=1 as well.' % NPROC)
    a = ap.parse_args(argv)
    print(dc.banner())
    print('[evidence] nlive=%d dlogz=%g seed=%d  A~U(-%g,%g) two-sided  %s(%g,%g)'
          % (NLIVE, DLOGZ, SEED, A_MAX, A_MAX,
             'ln z1~U' if Z1_PRIOR == 'log' else 'z1~U', Z1_MIN, Z1_MAX))
