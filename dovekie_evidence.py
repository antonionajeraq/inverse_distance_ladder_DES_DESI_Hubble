MODELS = ('lcdm', 'exp', 'cpl')
NDIM = {'lcdm': 3, 'exp': 5, 'cpl': 5}
PARAM_NAMES = {'lcdm': ('Om', 'H0', 'rd'),
               'exp': ('Om', 'H0_LCDM', 'A', 'z1', 'rd'),
               'cpl': ('Om', 'H0', 'w0', 'wa', 'rd')}


def _E_lcdm(z, Om):
    return np.sqrt(Om * (1.0 + z) ** 3 + (1.0 - Om))


def H_of_grid(theta, model):
    """H(z) on ZGRID for the parameter vector of `model`."""
    if model == 'lcdm':
        Om, H0, _rd = theta
        return H0 * _E_lcdm(ZGRID, Om)
    if model == 'cpl':
        Om, H0, w0, wa, _rd = theta
        zp = ZGRID / (1.0 + ZGRID)
        de = (1.0 + ZGRID) ** (3.0 * (1.0 + w0 + wa)) * np.exp(-3.0 * wa * zp)
        return H0 * np.sqrt(Om * (1.0 + ZGRID) ** 3 + (1.0 - Om) * de)
    if model == 'exp':
        Om, H0L, A, z1, _rd = theta
        return H0L * _E_lcdm(ZGRID, Om) + A * np.exp(-ZGRID / z1)
    raise ValueError('unknown model %r' % model)


def _build_dc(Hgrid):
    return c_km_s * cumulative_trapezoid(1.0 / Hgrid, ZGRID, initial=0.0)


def make_ptform(model):
    def ptform(u):
        x = np.asarray(u)
        Om = OM_LO + (OM_HI - OM_LO) * x[0]
        H0 = H0_LO + (H0_HI - H0_LO) * x[1]
        if model == 'lcdm':
            return np.array([Om, H0, norm.ppf(x[2], dc.BASELINE['RD_PLANCK'],
                                              dc.BASELINE['SIG_RD'])])
        rd = norm.ppf(x[4], dc.BASELINE['RD_PLANCK'], dc.BASELINE['SIG_RD'])
        if model == 'cpl':
            return np.array([Om, H0,
                             W0_LO + (W0_HI - W0_LO) * x[2],
                             WA_LO + (WA_HI - WA_LO) * x[3], rd])
        z1 = (Z1_MIN * (Z1_MAX / Z1_MIN) ** x[3] if Z1_PRIOR == 'log'
              else Z1_MIN + (Z1_MAX - Z1_MIN) * x[3])
        return np.array([Om, H0,
                         -A_MAX + 2.0 * A_MAX * x[2], z1, rd])
    return ptform


