def _mu_kin(z, H0, q0=Q0_KIN, j0=J0_KIN):
    """The kinematic distance-modulus template the anchor analyses apply."""
    z = np.asarray(z, float)
    DL = (c_km_s * z / H0) * (1.0 + 0.5 * (1.0 - q0) * z
                              - (1.0 - q0 - 3.0 * q0 ** 2 + j0) * z ** 2 / 6.0)
    return 5.0 * np.log10(DL) + 25.0


def _mu_model(z, Hg):
    DL = (1.0 + np.asarray(z, float)) * np.interp(z, ZGRID, _build_dc(Hg))
    return 5.0 * np.log10(DL) + 25.0


def anchor_infer(Hg, anchor, H0_ref=70.0):
    """The H0 the anchor's OWN estimator returns for a universe with expansion history Hg.

    Since D_L^kin ~ 1/H0 the template shifts rigidly in magnitude, the least-squares
    solution is closed form:

        H0_inferred = H0_ref * 10 ** ( -<mu_model - mu_kin(.; H0_ref)> / 5 )

    over the anchor's own redshift window.  This is what makes the comparison honest: a
    transition that completes below an anchor's window is largely INVISIBLE to it, so the
    model must not be credited with fitting an anchor its own predictions would miss.

    The average is EQUAL-WEIGHT, and that is an approximation, not the published
    estimator.  Each anchor analysis weights its own objects by their own uncertainties,
    covariance and selection, none of which is distributed with the redshift lists used
    here.  So this is the anchor's estimator applied to an equal-weight window rather than
    the anchor's estimator itself.  It is exact for GW170817, which has one object; for
    the Jensen, Vogl and Breuval windows it assumes the reweighting does not move the
    window average, which is the assumption to check if an anchored lnB is ever quoted to
    better than ~0.1.

    `_mu_model` and `_mu_kin` also use ONE redshift per object where the supernova
    likelihood distinguishes z_HD from z_HEL.  That is forced: the anchor catalogues
    publish their Hubble-flow redshift alone, with no heliocentric twin to pair it with.
    At z <= 0.15 the two differ by <~ 1e-3 in (1+z), i.e. <~ 0.002 mag, which is inside
    every anchor uncertainty here by two orders of magnitude."""
    z = ANCHOR_Z.get(anchor)
    if z is None:
        raise ValueError('anchor %r has no verified Hubble-flow redshift window, so the '
                         'forward model cannot be applied.' % anchor)
    return H0_ref * 10.0 ** (-np.mean(_mu_model(z, Hg) - _mu_kin(z, H0_ref)) / 5.0)


