SAMPLES = {
    'des_only': ('des_only', False),
    'full': ('full', False),
    'full_dleg': ('full', True),
}

_BAO = None
_CC = None


def _static_blocks():
    """The DESI vector and the chronometer block, built once from dovekie_cosmography."""
    global _BAO, _CC
    if _BAO is None:
        O, Cov, zs, kinds = dc.bao_vector()
        z_uni = np.unique(zs)
        col, is_dm, is_dh, _ = dc._selectors(zs, kinds, z_uni)
        _BAO = dict(O=O, Cinv=np.linalg.inv(Cov), z_uni=z_uni,
                    col=col, is_dm=is_dm, is_dh=is_dh)
        z, H, C = dc.cc_block()
        _CC = dict(z=z, H=H, Cinv=np.linalg.inv(C))
    return _BAO, _CC


def make_loglike(sample, model, anchor='none'):
    """The joint log-likelihood for one cell of the grid.

    chi2 = chi2_SN + chi2_BAO + chi2_CC (+ chi2_anchor)

    Planck is NOT in that sum, and must not be put back.  r_d enters through
    `make_ptform`, which draws it as N(147.05, 0.30) -- that Gaussian IS the Planck
    constraint, and it is already normalised inside the evidence integral.  Adding a
    chi2_rd term on top of it imposed Planck TWICE and narrowed the effective constraint
    to sigma/sqrt(2); the chains written before 2026-08-18 show it directly, with
    sigma(r_d) = 0.210-0.214 against 0.30/sqrt(2) = 0.2121.  test_repo pins the count.

    The supernova block marginalises the global magnitude offset analytically, and for
    `full_dleg` the legacy zero-point too."""
    dsname, free_delta = SAMPLES[sample]
    d = dc.sn_dataset(dsname)
    # z_HD drives the comoving integral, z_HEL the (1+z) luminosity prefactor.  They are
    # NOT interchangeable -- see dc.sn_apparent_mag.
    z_sn, zhel_sn, mu = d['z'], d['zhel'], d['mu']
    invC = np.linalg.inv(d['cov'])
    one = np.ones_like(mu)
    Cinv_one = invC @ one
    C_oo = float(one @ Cinv_one)

    # ---- rank-2 nuisance basis -------------------------------------------------------
    # The published likelihood marginalises ONE offset, V = [1], analytically:
    #     chi2 = r'C^-1 r - (1'C^-1 r)^2 / (1'C^-1 1)
    # Freeing the legacy zero-point as well is the SAME construction with V = [1, u_leg]:
    #     chi2 = r'C^-1 r - (V'C^-1 r)' G^-1 (V'C^-1 r),   G = V'C^-1 V   (2x2, theta-free)
    # EXACT, and it costs no extra sampled dimension.
    u_leg = G_inv = None
    ln_delta_norm = 0.0
    if free_delta:
        u_leg = (d['idsurvey'] != dc.DES_IDSURVEY).astype(float)
        if u_leg.sum() == 0:
            raise ValueError('sample %r has no legacy SNe -- Delta is unidentified'
                             % sample)
        V = np.column_stack([one, u_leg])
        G_inv = np.linalg.inv(V.T @ (invC @ V))
        sig_delta = float(np.sqrt(G_inv[1, 1]))
        # Delta gets a PROPER prior U(-DELTA_MAX, DELTA_MAX) so its contribution to lnZ is
        # a definite number.  The global offset stays improper-flat, exactly as published,
        # which is why only lnB10 within a sample is ever quoted.
        ln_delta_norm = float(np.log(sig_delta * np.sqrt(2.0 * np.pi)
                                     / (2.0 * DELTA_MAX)))
        Cinv_u = invC @ u_leg

    bao, cc = _static_blocks()
    terms = anchor_terms(anchor)

    def loglike(theta):
        Hg = H_of_grid(theta, model)
        if np.any(Hg <= 0) or np.any(~np.isfinite(Hg)):
            return -1e30
        Dc = _build_dc(Hg)
        if np.any(np.diff(Dc) <= 0):
            return -1e30

        r = mu - dc.sn_apparent_mag(0.0, zhel_sn, np.interp(z_sn, ZGRID, Dc))
        Cinv_r = invC @ r
        A_ = float(r @ Cinv_r)
        ln_nuis = 0.0
        if u_leg is None:
            B_ = float(r @ Cinv_one)
            chi2_sn = A_ - B_ * B_ / C_oo
        else:
            g = np.array([float(r @ Cinv_one), float(r @ Cinv_u)])
            Ginv_g = G_inv @ g
            chi2_sn = A_ - float(g @ Ginv_g)
            s_d = np.sqrt(G_inv[1, 1])
            frac = (norm.cdf((DELTA_MAX - Ginv_g[1]) / s_d)
                    - norm.cdf((-DELTA_MAX - Ginv_g[1]) / s_d))
            ln_nuis = ln_delta_norm + float(np.log(max(frac, 1e-300)))

        rd = theta[-1]                 # prior-imposed; see the docstring, no chi2_rd here
        DM = np.interp(bao['z_uni'], ZGRID, Dc)
        DH = c_km_s / np.interp(bao['z_uni'], ZGRID, Hg)
        DV = (bao['z_uni'] * DM ** 2 * DH) ** (1.0 / 3.0)
        pred = np.where(bao['is_dm'], DM[bao['col']],
                        np.where(bao['is_dh'], DH[bao['col']], DV[bao['col']])) / rd
        db = pred - bao['O']
        chi2_bao = float(db @ bao['Cinv'] @ db)

        rc = np.interp(cc['z'], ZGRID, Hg) - cc['H']
        chi2_cc = float(rc @ cc['Cinv'] @ rc)

        chi2_anc = 0.0
        for comp, a_mean, a_sig in terms:
            chi2_anc += ((anchor_infer(Hg, comp) - a_mean) / a_sig) ** 2

        return -0.5 * (chi2_sn + chi2_bao + chi2_cc + chi2_anc) + ln_nuis

    def delta_moments(theta):
        """(Delta_hat, sigma_Delta) conditional on theta.

        Delta is marginalised analytically and never sampled, but its posterior is still
        available in closed form: given theta the offsets are Gaussian with mean
        G^-1 V'C^-1 r and covariance G^-1, so over posterior draws the law of total
        variance gives
            E[Delta]   = <Delta_hat>
            Var[Delta] = <sigma_Delta^2> + Var(Delta_hat)
        This is not a Laplace approximation.  It does neglect the |Delta| <= DELTA_MAX
        truncation that the marginalised LIKELIHOOD above accounts for exactly: with
        sigma_Delta ~ 0.04 mag against a one-magnitude boundary the correction is ~1e-90
        of the mass, i.e. below every digit ever printed, but these are Gaussian moments
        and not truncated-normal ones and the docstring should say so."""
        if u_leg is None:
            return np.nan, np.nan
        Hg = H_of_grid(theta, model)
        if np.any(Hg <= 0) or np.any(~np.isfinite(Hg)):
            return np.nan, np.nan
        r = mu - dc.sn_apparent_mag(0.0, zhel_sn,
                                    np.interp(z_sn, ZGRID, _build_dc(Hg)))
        g = np.array([float(r @ Cinv_one), float(r @ Cinv_u)])
        return float((G_inv @ g)[1]), float(np.sqrt(G_inv[1, 1]))

    loglike.delta_moments = delta_moments
    loglike.free_delta = bool(free_delta)
    return loglike


