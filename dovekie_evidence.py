def cell_name(sample, anchor, model):
    # The log-z1 run must NOT land on the uniform run's file.  Only `exp` is suffixed:
    # lcdm and cpl are unaffected by the z1 prior, so they keep their names and their
    # cached cells, and lnB10 under either prior is measured against the same lnZ_LCDM.
    name = '%s__%s__%s' % (sample, anchor, model)
    if model == 'exp' and Z1_PRIOR != 'uniform':
        name += '__%sz1' % Z1_PRIOR
    return name


# The likelihood is a closure over the data blocks and so cannot be pickled.  Workers are
# therefore forked AFTER it is built and reach it through these module globals, which fork
# inheritance gives them for free; the picklable module-level wrappers below are what
# actually travel down dynesty's task queue.  The prior transform needs the same treatment
# -- dynesty pickles BOTH callables, not just the likelihood.
_POOL_LL = None
_POOL_PT = None


def _pool_loglike(theta):
    return _POOL_LL(theta)


def _pool_ptform(u):
    return _POOL_PT(u)


def _blas_threads_pinned():
    """True if every BLAS thread-count variable is set to 1."""
    keys = ('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS')
    return all(os.environ.get(k) == '1' for k in keys)


def run_cell(sample, anchor, model, nlive=None, dlogz=None, seed=None, quiet=False,
             nproc=None):
    import dynesty
    nlive = NLIVE if nlive is None else nlive
    dlogz = DLOGZ if dlogz is None else dlogz
    seed = SEED if seed is None else seed
    nproc = NPROC if nproc is None else nproc

    if not _blas_threads_pinned():
        print('[evidence] WARNING: BLAS threads are not pinned to 1.  This likelihood is '
              'up to 9x SLOWER threaded.  Re-launch with '
              'OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1.')

    ll = make_loglike(sample, model, anchor)
    pt = make_ptform(model)

    pool = None
    if nproc > 1:
        import multiprocessing as mp
        global _POOL_LL, _POOL_PT
        _POOL_LL, _POOL_PT = ll, pt                     # inherited by the forked workers
        pool = mp.get_context('fork').Pool(nproc)
        print('[evidence] likelihood queue over %d worker processes' % nproc)

    try:
        skw = sampler_kwargs()
        if skw:
            print('[evidence] proposal override: %s'
                  % ', '.join('%s=%r' % kv for kv in sorted(skw.items())))
        ns = dynesty.NestedSampler(_pool_loglike if pool is not None else ll,
                                   _pool_ptform if pool is not None else pt,
                                   NDIM[model], nlive=nlive,
                                   rstate=np.random.default_rng(seed),
                                   pool=pool, queue_size=nproc if pool else None,
                                   **skw)
        ns.run_nested(dlogz=dlogz, print_progress=not quiet)
        res = ns.results
    finally:
        if pool is not None:
            pool.close()
            pool.join()
            _POOL_LL = _POOL_PT = None
    w = np.exp(res.logwt - res.logz[-1])
    w = w / w.sum()
    samples = res.samples

    out = dict(sample=sample, anchor=anchor, model=model,
               nlive=nlive, dlogz=dlogz, seed=seed,
               logz=float(res.logz[-1]), logz_err=float(res.logzerr[-1]),
               # res.ncall is PER-ITERATION, not a total -- int() on it raises.
               ncall=int(np.sum(res.ncall)), niter=int(res.niter),
               proposal=sampler_kwargs() or 'auto',
               params=list(PARAM_NAMES[model]))
    for i, nm in enumerate(PARAM_NAMES[model]):
        m = float(np.sum(w * samples[:, i]))
        out[nm + '_mean'] = m
        out[nm + '_std'] = float(np.sqrt(np.sum(w * (samples[:, i] - m) ** 2)))

    # H(0), the model's own present-day expansion rate.  For `exp` this is H0_LCDM + A and
    # is NOT the background H0_LCDM, which reads 68-70 even in cells reaching 73.  Both are
    # reported: the H0 column of Table 2 is H(0).
    if model == 'exp':
        h0 = samples[:, 1] + samples[:, 2]
        out['P_A_gt_0'] = float(np.sum(w * (samples[:, 2] > 0)))
    else:
        h0 = samples[:, 1]
    out['H0_at_0_mean'] = float(np.sum(w * h0))
    out['H0_at_0_std'] = float(np.sqrt(np.sum(w * (h0 - out['H0_at_0_mean']) ** 2)))

    if ll.free_delta:
        dh = np.array([ll.delta_moments(t)[0] for t in samples])
        ds = np.array([ll.delta_moments(t)[1] for t in samples])
        ok = np.isfinite(dh)
        wm = w[ok] / w[ok].sum()
        mean = float(np.sum(wm * dh[ok]))
        # law of total variance: E[sigma^2] + Var(Delta_hat)
        var = float(np.sum(wm * ds[ok] ** 2)
                    + np.sum(wm * (dh[ok] - mean) ** 2))
        out['Delta_mean'], out['Delta_std'] = mean, float(np.sqrt(var))

    return out, samples, w


def cache_extra(anchor, model):
    """The settings a cached evidence cell must agree on, but that BASELINE never sees.

    dc._CACHE_KEYS covers the model and the data; every knob below lives in THIS module,
    so none of it could invalidate a cache.  The consequence was concrete: a scouting run
    at DLOGZ=1 wrote a cell that a production run at DLOGZ=0.01 would happily reload and
    report as converged.  The prior bounds are here for the same reason -- they set the
    prior volume, which is charged directly to lnB10."""
    e = {
        'NLIVE': NLIVE, 'DLOGZ': DLOGZ, 'SEED': SEED,
        'ZMAX': ZMAX, 'NZ': int(ZGRID.size),
        'H0_LO': H0_LO, 'H0_HI': H0_HI,
        'OM_LO': OM_LO, 'OM_HI': OM_HI,
        'DELTA_MAX': DELTA_MAX,
        'anchor': anchor,
        'anchor_terms': [[c, float(m), float(sg)] for c, m, sg in anchor_terms(anchor)],
        'anchor_windows': {c: [float(np.min(ANCHOR_Z[c])), float(np.max(ANCHOR_Z[c])),
                               int(np.size(ANCHOR_Z[c])), float(np.mean(ANCHOR_Z[c]))]
                           for c, _m, _s in anchor_terms(anchor)},
        'Q0_KIN': Q0_KIN, 'J0_KIN': J0_KIN,
    }
    # The PROPOSAL, and why it is here CONDITIONALLY.  `cache_load` treats a key the
    # cached manifest does not carry as a MISMATCH, so adding these unconditionally would
    # refuse all 26 cells written before the knob existed and force the whole grid to be
    # re-run for a change that cannot move lnZ.  Adding them only when they are non-default
    # makes the asymmetry the useful way round:
    #     default run   -> not requested, so not compared; every existing cell still loads
    #     SAMPLER=rslice-> requested, so a cell written by the default proposal is ABSENT
    #                      on these keys and is REFUSED, which is what forces the re-run
    # The residual case -- a default run reloading a cell written under an override -- is
    # legitimate, because the two are estimates of the same integral, and `task_grid`
    # prints the provenance on load rather than letting it pass silently.
    e.update(sampler_kwargs())
    if model == 'exp':
        e.update(A_MAX=A_MAX, Z1_MIN=Z1_MIN, Z1_MAX=Z1_MAX)
        # CONDITIONAL for the same reason as the proposal keys above: adding it always
        # would refuse every exp cell written before the knob existed.
        if Z1_PRIOR != 'uniform':
            e.update(Z1_PRIOR=Z1_PRIOR)
    elif model == 'cpl':
        e.update(W0_LO=W0_LO, W0_HI=W0_HI, WA_LO=WA_LO, WA_HI=WA_HI)
    return e


def task_grid(samples=None, anchors=None, models=None, only=None, recompute=False,
              quiet=False, nproc=None):
    samples = samples or ('des_only', 'full', 'full_dleg')
    anchors = anchors or ('none', 'lfree3', 'breuval')
    models = models or MODELS
    cells = [(s, a, m) for s in samples for a in anchors for m in models]
    if only:
        want = set(only)
        cells = [c for c in cells if '/'.join(c) in want]
        if not cells:
            raise ValueError('no cell matched --only %s' % ', '.join(sorted(want)))
    done = []
    for s, a, m in cells:
        cell = cell_name(s, a, m)
        extra = cache_extra(a, m)
        cached = None if recompute else dc.cache_load('evidence', cell, ignore_p=True,
                                                      extra=extra)
        if cached is not None:
            summ = json.loads(str(cached['summary_json']))
            prop = summ.get('proposal', 'auto')
            print('[evidence] %s (cached)%s'
                  % (cell, '' if prop in ('auto', {}) else
                     '  [written with proposal %r, not dynesty\'s default]' % (prop,)))
            done.append(summ)
            continue
        print('[evidence] %s  nested sampling...' % cell)
        out, draws, w = run_cell(s, a, m, quiet=quiet, nproc=nproc)
        dc.cache_save('evidence', cell, extra=extra, samples=draws, weights=w,
                      summary_json=json.dumps(out))
        done.append(out)
    return done


