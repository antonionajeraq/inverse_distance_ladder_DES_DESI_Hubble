def load_grid(samples=None, anchors=None, models=None):
    samples = samples or ('des_only', 'full', 'full_dleg')
    anchors = anchors or ('none', 'lfree3', 'breuval')
    models = models or MODELS
    R = {}
    for s in samples:
        for a in anchors:
            for m in models:
                c = dc.cache_load('evidence', cell_name(s, a, m), ignore_p=True,
                                  extra=cache_extra(a, m))
                if c is not None:
                    R[(s, a, m)] = json.loads(str(c['summary_json']))
    return R


