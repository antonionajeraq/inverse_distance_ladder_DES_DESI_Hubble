# A IS TWO-SIDED ON PURPOSE.  A one-sided prior A >= 0 pre-commits to the direction the
# anchor is meant to test, and DES+legacy in fact prefers A < 0 -- a low-redshift DEFICIT.
# Reporting a Bayes factor for "a rise" against data that want a fall would be a rigged
# comparison.  The cost is that roughly half the prior volume is spent where no solution
# to the tension lives, and that cost is REAL and is part of what lnB10 measures: with
# sigma(A) ~ 3, a box 20 wide charges M1 about 0.9 nat of Occam volume.  So a mildly
# negative lnB10 under no anchor is the Bayes factor reporting prior volume the data never
# constrain, NOT evidence against a transition.  The paper says so, and P(A>0) is reported
# beside every lnB10 for exactly this reason.
#
# Z1_MIN is a NUMERICAL floor (z1 -> 0 makes exp(-z/z1) a step the grid cannot resolve),
# not a physical statement; it is 0.2% of the prior volume.
#
# THE SHAPE OF THE z1 PRIOR IS NOT COSMETIC.  Over THESE limits a log-uniform prior on z1
# puts ln(0.1/0.001)/ln(0.5/0.001) = 74% of its mass below 0.1 and has a median of 0.0224,
# i.e. most of it sits on transitions that complete below the survey floor and are
# undetectable BY CONSTRUCTION -- pure Occam penalty against M1.  Uniform puts most of its
# mass in the region the analysis can actually probe (median 0.2505).  This is a choice, it
# moves lnB10 on its own, and it is reported as a choice: run both with Z1_PRIOR.


